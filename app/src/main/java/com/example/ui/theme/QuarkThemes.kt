/** 16-color ANSI + default fg/bg/cursor palette for the integrated terminal. */
data class TerminalColorPalette(
  val background: Int,
  val foreground: Int,
  val cursor: Int,
  val ansi16: IntArray,
)

/** Complete theme bundling UI chrome, syntax editor colors, and terminal palette. */
