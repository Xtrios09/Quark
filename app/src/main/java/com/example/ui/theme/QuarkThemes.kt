/** UI chrome colors for the IDE shell. */
data class UiColorTokens(
  val activityRailBg: Color,
  val sidePanelBg: Color,
  val editorBg: Color,
  val tabBarBg: Color,
  val tabActiveBg: Color,
  val tabInactiveBg: Color,
  val statusBarBg: Color,
  val statusBarFg: Color,
  val bottomPanelBg: Color,
  val border: Color,
  val accent: Color,
  val onAccent: Color,
  val textPrimary: Color,
  val textSecondary: Color,
  val textMuted: Color,
  val selectionHighlight: Color,
  val danger: Color,
  val warning: Color,
  val success: Color,
